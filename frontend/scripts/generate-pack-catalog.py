#!/usr/bin/env python3
"""Generate the browser-safe pack catalogue from the shared Python manifest."""

from __future__ import annotations

import json
import sys
from pathlib import Path


FRONTEND_DIR = Path(__file__).resolve().parents[1]
REPO_ROOT = FRONTEND_DIR.parent
OUTPUT_PATH = FRONTEND_DIR / "src" / "generated" / "packCatalog.ts"

if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from shared.manifests import PACKS  # noqa: E402


def main() -> None:
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    serialized_packs = json.dumps(PACKS, ensure_ascii=False, indent=2)
    OUTPUT_PATH.write_text(
        "// Generated by frontend/scripts/generate-pack-catalog.py. Do not edit.\n"
        'import type { PackCatalogEntry } from "../packCatalogSnapshot";\n\n'
        f"export const PACK_CATALOG: PackCatalogEntry[] = {serialized_packs};\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
